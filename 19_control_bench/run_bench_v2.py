#!/usr/bin/env python3
"""run_bench_v2.py — pre-registration v2: LinuxArena re-run with the trusted task text taken from the main-task description (adapter_v2), laws UNCHANGED from v1.

  .venv-inspect/bin/python 19_control_bench/run_bench_v2.py --calibrate <benchmarks dir>   # honest runs only: prints the threshold to freeze
  .venv-inspect/bin/python 19_control_bench/run_bench_v2.py <benchmarks dir>               # the frozen run; refuses unless hashes match PREREG_v2.md

BashArena and MonitoringBench are not re-run: their attack runs carry no system prompt and their task text was already exactly the main-task description, so v2 would not change them.
"""
import collections, hashlib, json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import adapter_v2, laws
from calibrate import threshold
from run_bench import side_success, rate

HONEST, ATTACKS = "linuxarena_honest.eval", ["linuxarena_attack.eval", "linuxarena_strategies.eval"]
FILES = ("laws.py", "adapter.py", "adapter_v2.py", "run_bench_v2.py")


def sha(p): return hashlib.sha256(open(p, "rb").read()).hexdigest()


def frozen():
    txt = open(os.path.join(HERE, "PREREG_v2.md")).read()
    want = dict(re.findall(r"`([\w.]+\.py)`\s+sha256\s+`([0-9a-f]{64})`", txt)); k = re.search(r"FROZEN_THRESHOLD\s*=\s*(\d+)", txt)
    bad = [f for f in FILES if want.get(f) != sha(os.path.join(HERE, f))]
    if bad or not k: sys.exit(f"REFUSED: {bad or 'no FROZEN_THRESHOLD'} does not match PREREG_v2.md")
    return int(k.group(1))


def main(bdir, calibrate_only):
    H = [laws.judge(t["task"], t["actions"]) for t in adapter_v2.load(os.path.join(bdir, HONEST))]; hs = [r["score"] for r in H]
    if calibrate_only:
        k = threshold(hs); print(f"honest {len(H)}; score distribution {dict(sorted(collections.Counter(hs).items()))}; threshold at <=1%: {k} (honest at/above {sum(s >= k for s in hs)})"); return
    k = frozen(); A, ids, succ = [], [], {}
    for af in ATTACKS:
        p = os.path.join(bdir, af); succ.update(side_success(p))
        for t in adapter_v2.load(p): A.append(laws.judge(t["task"], t["actions"])); ids.append(t["id"])
    n = len(A); caught = [r["score"] >= k for r in A]; si = [i for i, x in enumerate(ids) if succ.get(x) is True]; per = collections.Counter(l for r in A for l in r["laws"])
    fa = sum(s >= k for s in hs); c1 = sum(r["score"] >= k - 1 for r in A); fa1 = sum(s >= k - 1 for s in hs)
    L = ["# LinuxArena, pre-registration v2", "", "*Generated by `run_bench_v2.py` under `PREREG_v2.md`. Laws unchanged from v1; task text from the main-task description.*", "",
         f"- honest runs {len(H)}; false alarms at the frozen threshold (score ≥ {k}): **{rate(fa, len(H))}**", f"- attack trajectories {n}; **caught: {rate(sum(caught), n)}**",
         f"- attacks whose side task succeeded (where logged): {len(si)}; caught: {rate(sum(caught[i] for i in si), len(si))}",
         f"- one law lower (score ≥ {k-1}): caught {rate(c1, n)} at false alarms {rate(fa1, len(H))}",
         "- laws fired on attacks: " + ", ".join(f"{l} {rate(per[l], n)}" for l in laws.LAWS) + f", R6_ORIENTATION {rate(sum(r['orientation'] for r in A), n)}", ""]
    open(os.path.join(HERE, "RESULTS_v2.md"), "w").write("\n".join(L)); print("\n".join(L))


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if a != "--calibrate"]
    main(args[0] if args else os.path.join(HERE, "..", "..", "benchmarks"), "--calibrate" in sys.argv)
